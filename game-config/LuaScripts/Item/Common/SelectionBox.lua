function SelectionBox:OnUse(scene, item, player, otherParams)
    local dialog = GUI:CreateItemDialog()
    dialog:AddText("Bằng hữu có thể nhận một trong các vật phẩm dưới đây.")
    dialog:AddText("")
    dialog:AddText(
        "Ấn vào ô vật phẩm để xem thông tin chi tiết. Trong khung thông tin vật phẩm, ấn CHỌN để lựa chọn vật phẩm. Sau đó ấn XÁC NHẬN để nhận vật phẩm.")
    dialog:AddText("")

    local config = SELECTION_BOX_CONFIG[item:GetItemID()]
    if config == nil then
        dialog:AddText("Vật phẩm lỗi, vui lòng thử lại sau!")
        dialog:Show(item, player)
        return
    end

    for k, v in ipairs(config) do
        local isValidItem = true
        if v.Require_Series ~= nil then
            local playerSeries = Player:GetSeries(player)
            if playerSeries ~= v.Require_Series then
                isValidItem = false
            end
        end

        if v.Require_Sex ~= nil then
            local playerSex = player:GetSex()
            if playerSex ~= v.Require_Sex then
                isValidItem = false
            end
        end

        if isValidItem then
            local bindingState = 1
            local numberToAdd = 1

            if v.Number ~= nil then
                numberToAdd = v.Number
            end

            if v.Binding ~= nil then
                bindingState = v.Binding
            end

            dialog:AddItem(v.ItemID, numberToAdd, bindingState)
        end
    end

    dialog:Show(item, player)
end

function SelectionBox:OnSelection(scene, item, player, selectionID, otherParams)

end

function SelectionBox:OnItemSelected(scene, item, player, itemSelection)
    GUI:CloseDialog(player)

    local itemID = itemSelection:GetItemID()
    local itemCount = itemSelection:GetItemCount()
    local binding = itemSelection:GetBinding()

    local neededSlot = Player:GetTotalSpacesNeedToTakeItem(itemID, itemCount)

    if not Player:HasFreeBagSpaces(player, neededSlot) then
        GUI:ShowMessageBox(player, "Thông báo", "Bằng hữu cần " .. neededSlot ..
            " ô trống trong túi đồ để nhận vật phẩm.")
        return
    end

    Player:RemoveItem(player, item:GetID())
    Player.AddItemLuaAndNotify(player, itemID, itemCount, -1, binding)
end
