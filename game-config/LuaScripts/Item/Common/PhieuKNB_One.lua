function PhieuKNB:OnUse(scene, item, player, otherParams)
	local total = player:IsHasItem(item:GetItemID())
	GUI:ShowMessageBox(player, "Thông báo", "Bạn có thể đổi được " .. total .. " KNB. Ấn OK để tiến hành đổi.",
		function ()
			if Player:RemoveItem(player, item:GetItemID(), total) then
				Player:AddMoney(player, total, 2, "PHIEU-1-KNB")
			else
				GUI:ShowMessageBox(player, "Thông báo", "Đã có lỗi xảy ra. Vui lòng liên hệ với quản trị viên để được hỗ trợ.")
			end
		end,
		function ()
		end
	)
end

